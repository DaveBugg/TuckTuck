-- Напоминание в САМ день оплаты.
--
-- Набор по умолчанию был «за 2 суток и за сутки», и в день списания панель
-- молчала — именно тогда, когда ещё можно успеть заплатить. Новым ресурсам это
-- чинит код; уже заведённым добавляем напоминание здесь, иначе правка коснулась
-- бы только тех, кого заведут после обновления.
--
-- Пара (resourceId, daysBefore) уникальна, поэтому повторный прогон и ресурсы,
-- где нулевое напоминание уже стоит, просто ничего не изменят.
INSERT INTO "PaymentReminder" ("id", "resourceId", "daysBefore", "isActive", "createdAt")
SELECT gen_random_uuid(), r."id", 0, true, NOW()
FROM "Resource" r
ON CONFLICT ("resourceId", "daysBefore") DO NOTHING;
