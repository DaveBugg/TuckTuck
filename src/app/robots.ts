import type { MetadataRoute } from "next";

// Панель закрыта от индексации целиком: за логином лежат суммы, даты оплат,
// адреса серверов и имена провайдеров. Поисковику там делать нечего, а сам
// факт «такая-то панель живёт на таком-то домене» — уже лишняя подсказка.
//
// Слой первый из трёх: ещё есть мета-тег в layout.tsx и заголовок X-Robots-Tag
// из next.config.js. robots.txt соблюдают не все, мета-тега нет у API-ответов,
// а заголовок из Caddy пропадает, если панель поставили за свой прокси.
export default function robots(): MetadataRoute.Robots {
  return {
    rules: { userAgent: "*", disallow: "/" },
  };
}
