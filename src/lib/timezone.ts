// Часовой пояс проекта для нарезки суток в аналитике.
//
// Зачем: сутки резались по UTC, а смотрят на них по местному времени. Депозит
// в 23:41 UTC — это 02:41 МСК следующего дня: панель относила его ко вчера,
// источник к сегодня, и дневные цифры расходились (на проде — 569 против 670).
// Каждую ночь с 21:00 до 24:00 UTC это выглядело как потеря данных, хотя данные
// на месте.
//
// БЕЗОПАСНОСТЬ: имя пояса подставляется в SQL как ЛИТЕРАЛ — и в Postgres
// (AT TIME ZONE), и в ClickHouse (toDate(ts, 'зона')). Параметризовать его
// нельзя: в ClickHouse зона обязана быть константой времени компиляции запроса.
// Поэтому значение проходит через проверку ниже, а не берётся из формы как есть.

/**
 * Проверенное имя пояса или null.
 *
 * Проверяем СИСТЕМНЫМ списком (Intl), а не своим перечнем: свой пришлось бы
 * поддерживать вручную и он всё равно отстанет от tzdata. Плюс жёсткий формат
 * поверх — Intl принимает и такие формы, как "UTC+3", а нам в SQL нужна только
 * та, что обе базы понимают одинаково.
 */
export function safeTimezone(tz: unknown): string | null {
  if (typeof tz !== "string") return null;
  const v = tz.trim();
  if (!v) return null;
  // Только буквы, цифры, _ + / − разделители: кавычка или пробел сюда не пройдут.
  if (!/^[A-Za-z][A-Za-z0-9_+-]*(\/[A-Za-z0-9_+-]+)*$/.test(v)) return null;
  if (v.length > 64) return null;
  try {
    // Бросит RangeError, если пояса не существует.
    new Intl.DateTimeFormat("en-US", { timeZone: v });
  } catch {
    return null;
  }
  return v;
}

/** Выражение «день» для Postgres. Двойное AT TIME ZONE: timestamptz → местное
 *  время → срез суток. Одинарное дало бы сдвиг в другую сторону. */
export function pgDayExpr(tz: string | null, col: string): string {
  const z = safeTimezone(tz);
  return z
    ? `date_trunc('day', ${col} AT TIME ZONE 'UTC' AT TIME ZONE '${z}')`
    : `date_trunc('day', ${col})`;
}
